package clipboard

import "testing"

func TestConcealedFromFormats(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name    string
		present []string
		dwords  map[string]uint32
		want    string
	}{
		{"nothing", nil, nil, ""},
		{"exclude", []string{winExcludeFromMonitors}, nil, ReasonConcealed},
		{"viewer ignore", []string{winViewerIgnore}, nil, ReasonConcealed},
		{"history no", []string{winCanIncludeInHistory}, map[string]uint32{winCanIncludeInHistory: 0}, ReasonConcealed},
		{"history yes", []string{winCanIncludeInHistory}, map[string]uint32{winCanIncludeInHistory: 1}, ""},
		{"cloud no", []string{winCanUploadToCloud}, map[string]uint32{winCanUploadToCloud: 0}, ReasonConcealed},
		{"cloud, unreadable value", []string{winCanUploadToCloud}, nil, ""},
		{"history yes, cloud no", []string{winCanIncludeInHistory, winCanUploadToCloud}, map[string]uint32{winCanIncludeInHistory: 1, winCanUploadToCloud: 0}, ReasonConcealed},
		{"unrelated", []string{"HTML Format"}, nil, ""},
	}
	for _, tt := range tests {
		if got := concealedFromFormats(tt.present, tt.dwords); got != tt.want {
			t.Errorf("%s: concealedFromFormats = %q, want %q", tt.name, got, tt.want)
		}
	}
}

func TestConcealedFromTypes(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name  string
		types []string
		want  string
	}{
		{"plain text", []string{"public.utf8-plain-text"}, ""},
		{"concealed", []string{"public.utf8-plain-text", "org.nspasteboard.ConcealedType"}, ReasonConcealed},
		{"1Password", []string{"com.agilebits.onepassword", "public.utf8-plain-text"}, ReasonConcealed},
		{"transient", []string{"org.nspasteboard.TransientType", "public.utf8-plain-text"}, ReasonTransient},
		{"auto-generated", []string{"org.nspasteboard.AutoGeneratedType"}, ReasonTransient},
		{"both", []string{"org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType"}, ReasonConcealed},
	}
	for _, tt := range tests {
		if got := concealedFromTypes(tt.types); got != tt.want {
			t.Errorf("%s: concealedFromTypes = %q, want %q", tt.name, got, tt.want)
		}
	}
}

// The marker is local knowledge, not content: the same bytes with and
// without it must read as the same clipboard to change detection.
func TestDigestIgnoresConcealed(t *testing.T) {
	t.Parallel()
	a := Content{ContentType: TypeText, Body: []byte("x")}
	b := a
	b.Concealed = ReasonConcealed
	if a.Digest() != b.Digest() {
		t.Error("Concealed changed the digest")
	}
}
