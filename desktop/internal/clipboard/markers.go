package clipboard

// Privacy markers: how an application that copies a secret asks clipboard
// tools to leave it alone.
//
// Both platforms have a convention, and the common password managers follow
// it. Nothing here identifies the application; the marker is the whole
// signal. The tables are plain data and the decisions pure functions so that
// they are tested on every OS, not just the one whose clipboard holds them.

// The reasons Content.Concealed carries. They are shown to the user, so they
// are sentences, and they say nothing about the content.
const (
	// ReasonConcealed is a copy its application marked private: a password
	// manager's, most often.
	ReasonConcealed = "Marked private by the app that copied it"

	// ReasonTransient is a copy its application marked as temporary or
	// generated (macOS): it asked clipboard tools not to keep it, and
	// uploading it to a relay is keeping it.
	ReasonTransient = "Marked temporary by the app that copied it"
)

// Windows registered clipboard formats with which an application marks its
// copy. Microsoft documents the first three for clipboard history and cloud
// clipboard; "Clipboard Viewer Ignore" is the older convention clipboard
// managers honour, set by KeePass among others.
const (
	winExcludeFromMonitors = "ExcludeClipboardContentFromMonitorProcessing"
	winCanIncludeInHistory = "CanIncludeInClipboardHistory"
	winCanUploadToCloud    = "CanUploadToCloudClipboard"
	winViewerIgnore        = "Clipboard Viewer Ignore"
)

// concealedFromFormats decides from the privacy formats present on a Windows
// clipboard. present names the ones offered; dwords holds the value of each
// one whose data was a DWORD.
//
// Exclude and Viewer Ignore mark by being there at all. The two Can… formats
// carry a DWORD, and only zero means no: an application may set them to one
// to say a copy is fine to keep.
func concealedFromFormats(present []string, dwords map[string]uint32) string {
	for _, name := range present {
		switch name {
		case winExcludeFromMonitors, winViewerIgnore:
			return ReasonConcealed
		case winCanIncludeInHistory, winCanUploadToCloud:
			if v, ok := dwords[name]; ok && v == 0 {
				return ReasonConcealed
			}
		}
	}
	return ""
}

// macOS pasteboard types with which an application marks its copy, from the
// nspasteboard.org convention and the managers that predate it.
var (
	macConcealedTypes = []string{
		"org.nspasteboard.ConcealedType",
		"com.agilebits.onepassword",
	}
	macTransientTypes = []string{
		"org.nspasteboard.TransientType",
		"org.nspasteboard.AutoGeneratedType",
		"de.petermaurer.TransientPasteboardType",
		"com.typeit4me.clipping",
		"Pasteboard generator type",
	}
)

// concealedFromTypes decides from a macOS pasteboard's type list. Concealed
// wins over transient: it is the stronger statement.
func concealedFromTypes(types []string) string {
	has := func(want []string) bool {
		for _, t := range types {
			for _, w := range want {
				if t == w {
					return true
				}
			}
		}
		return false
	}
	switch {
	case has(macConcealedTypes):
		return ReasonConcealed
	case has(macTransientTypes):
		return ReasonTransient
	}
	return ""
}
